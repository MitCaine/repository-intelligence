"""Authenticated evidence, attestation, completeness, and continuation contracts."""

from __future__ import annotations

from collections.abc import Mapping
from dataclasses import dataclass, field
import hmac
from typing import Any, Optional

from .authority import (
    _Authority,
    _binding_tuple,
    _require_authenticated_binding,
    _sign,
)
from .errors import ValidationError
from .identity import AuthenticatedBinding, IdentityBinding
from .validation import (
    _canonical_digest,
    _deep_freeze,
    _json_value,
    _optional_text,
    _require_exact_bool,
    _require_text,
)


@dataclass(frozen=True)
class ProviderClaim:
    """Provider-declared result and identity; never an attestation by itself."""

    result: Any
    binding: IdentityBinding
    declared_provenance: Optional[str] = None
    _raw_result: Any = field(default=None, init=False, repr=False, compare=False)

    def __post_init__(self) -> None:
        if not isinstance(self.binding, IdentityBinding):
            raise ValidationError("provider claim binding must be an IdentityBinding")
        if self.declared_provenance is not None:
            _require_text(self.declared_provenance, "declared_provenance")
        object.__setattr__(self, "_raw_result", self.result)
        object.__setattr__(self, "result", _deep_freeze(_json_value(self.result, "claim.result")))

    @property
    def result_digest(self) -> str:
        """Return the canonical digest of the claimed result."""

        return _canonical_digest(self.result)


@dataclass(frozen=True)
class HarnessObservation:
    """Result observation issued by a distinct harness-controlled path.

    ``provenance`` is generated by ``Harness.observe_result``.  Supplying a
    matching string to a caller-created observation cannot satisfy the private
    issuer signature or the observation-path checks.
    """

    result: Any
    binding: IdentityBinding
    observation_id: str
    provenance: str
    _authority: Optional[_Authority] = field(default=None, repr=False, compare=False)
    _signature: str = field(default="", repr=False, compare=False)
    _raw_result: Any = field(default=None, init=False, repr=False, compare=False)

    def __post_init__(self) -> None:
        if not isinstance(self.binding, IdentityBinding):
            raise ValidationError("observation binding must be an IdentityBinding")
        _require_text(self.observation_id, "observation_id", identifier=True)
        _require_text(self.provenance, "provenance")
        object.__setattr__(self, "_raw_result", self.result)
        object.__setattr__(
            self, "result", _deep_freeze(_json_value(self.result, "observation.result"))
        )

    @property
    def result_digest(self) -> str:
        """Return the canonical digest of the independently observed result."""

        return _canonical_digest(self.result)

    def is_authenticated(self) -> bool:
        """Return whether the observation was issued by its harness authority."""

        if (
            self._authority is None
            or type(self._signature) is not str
            or not isinstance(self.binding, AuthenticatedBinding)
            or self.binding._authority is not self._authority
            or not self.binding.is_authenticated()
        ):
            return False
        expected = _sign(
            self._authority,
            {
                "observation_id": self.observation_id,
                "provenance": self.provenance,
                "binding": self.binding.as_dict(),
                "result": self.result,
            },
        )
        return hmac.compare_digest(self._signature, expected)


@dataclass(frozen=True)
class ProviderAttestation:
    """Derived acceptance record joining a claim to independent observation."""

    claim_digest: str
    observation_digest: str
    binding: AuthenticatedBinding
    observation_id: str
    provenance: str
    accepted: bool
    _authority: Optional[_Authority] = field(default=None, repr=False, compare=False)
    _signature: str = field(default="", repr=False, compare=False)

    def __post_init__(self) -> None:
        _require_text(self.claim_digest, "claim_digest", identifier=True)
        _require_text(self.observation_digest, "observation_digest", identifier=True)
        _require_text(self.observation_id, "observation_id", identifier=True)
        _require_text(self.provenance, "provenance")
        _require_exact_bool(self.accepted, "accepted")

    def is_valid(
        self,
        claim: ProviderClaim,
        observation: HarnessObservation,
        expected_binding: AuthenticatedBinding,
    ) -> bool:
        """Recompute all acceptance inputs instead of trusting ``accepted``."""

        try:
            _validate_attestation_parts(claim, observation, expected_binding)
        except ValidationError:
            return False
        if (
            self._authority is None
            or observation._authority is not self._authority
            or not isinstance(self.binding, AuthenticatedBinding)
            or self.binding._authority is not self._authority
            or not self.binding.is_authenticated()
        ):
            return False
        expected = _sign(
            self._authority,
            {
                "claim_digest": claim.result_digest,
                "observation_digest": observation.result_digest,
                "binding": expected_binding.as_dict(),
                "observation_id": observation.observation_id,
                "provenance": observation.provenance,
                "accepted": True,
            },
        )
        return (
            self.accepted is True
            and self.claim_digest == claim.result_digest
            and self.observation_digest == observation.result_digest
            and self.binding == expected_binding
            and self.observation_id == observation.observation_id
            and self.provenance == observation.provenance
            and hmac.compare_digest(self._signature, expected)
        )


def _same_raw_object(left: Any, right: Any) -> bool:
    """Detect reuse of the same caller-owned container as claim and observation."""

    container = lambda value: isinstance(value, (Mapping, list, tuple, set))
    return container(left) and container(right) and left is right


def _validate_attestation_parts(
    claim: ProviderClaim,
    observation: HarnessObservation,
    expected_binding: AuthenticatedBinding,
) -> None:
    """Validate the non-serialized parts of an independent attestation."""

    if not isinstance(claim, ProviderClaim):
        raise ValidationError("provider claim is not a ProviderClaim")
    if not isinstance(observation, HarnessObservation):
        raise ValidationError("observation is not a HarnessObservation")
    _require_authenticated_binding(expected_binding, "expected_binding")
    if not observation.is_authenticated():
        raise ValidationError("observation lacks harness provenance")
    if _same_raw_object(claim._raw_result, observation._raw_result):
        raise ValidationError("claim and observation reuse the same raw result object")
    if claim.result_digest != observation.result_digest:
        raise ValidationError("claim and observation result disagree")
    if _binding_tuple(claim.binding) != _binding_tuple(expected_binding):
        raise ValidationError("provider claim has the wrong source binding")
    if _binding_tuple(observation.binding) != _binding_tuple(expected_binding):
        raise ValidationError("harness observation has the wrong source binding")
    if (
        not isinstance(observation.binding, AuthenticatedBinding)
        or observation.binding._authority is not expected_binding._authority
        or not observation.binding.is_authenticated()
    ):
        raise ValidationError("observation and expected binding have different issuers")


def validate_attestation(
    attestation: ProviderAttestation,
    claim: ProviderClaim,
    observation: HarnessObservation,
    expected_binding: AuthenticatedBinding,
) -> ProviderAttestation:
    """Validate an attestation and return it only when every join is proven."""

    if not isinstance(attestation, ProviderAttestation) or not attestation.is_valid(
        claim, observation, expected_binding
    ):
        raise ValidationError("provider attestation is not independently bound")
    return attestation


def attest_provider_result(
    claim: ProviderClaim,
    observation: HarnessObservation,
    expected_binding: AuthenticatedBinding,
) -> ProviderAttestation:
    """Create a derived accepted attestation from an issued observation path."""

    _validate_attestation_parts(claim, observation, expected_binding)
    authority = observation._authority
    if authority is None:
        raise ValidationError("observation has no harness authority")
    signature = _sign(
        authority,
        {
            "claim_digest": claim.result_digest,
            "observation_digest": observation.result_digest,
            "binding": expected_binding.as_dict(),
            "observation_id": observation.observation_id,
            "provenance": observation.provenance,
            "accepted": True,
        },
    )
    return ProviderAttestation(
        claim_digest=claim.result_digest,
        observation_digest=observation.result_digest,
        binding=expected_binding,
        observation_id=observation.observation_id,
        provenance=observation.provenance,
        accepted=True,
        _authority=authority,
        _signature=signature,
    )


@dataclass(frozen=True)
class ContinuationToken:
    """Authenticated continuation state for one coherent evidence session."""

    token_id: str
    evidence_session_id: str
    query: str
    operation: str
    coverage_universe_id: str
    view_id: str
    ordering: str
    lineage_id: str
    cursor: str
    binding: AuthenticatedBinding
    has_more: bool
    _authority: Optional[_Authority] = field(default=None, repr=False, compare=False)
    _signature: str = field(default="", repr=False, compare=False)

    def __post_init__(self) -> None:
        for name in (
            "token_id",
            "evidence_session_id",
            "query",
            "operation",
            "coverage_universe_id",
            "view_id",
            "ordering",
            "lineage_id",
            "cursor",
        ):
            _require_text(getattr(self, name), name, identifier=True)
        _require_authenticated_binding(self.binding, "continuation.binding")
        if self.operation not in {
            "resolve",
            "definitions",
            "references",
            "implementations",
            "dependencies",
            "search",
            "source",
        }:
            raise ValidationError("continuation.operation is unsupported")
        _require_exact_bool(self.has_more, "continuation.has_more")
        if self.has_more is not True:
            raise ValidationError("a continuation token must represent remaining evidence")

    def is_valid(self) -> bool:
        """Recompute the token signature and issuer binding."""

        if self._authority is None or self.binding._authority is not self._authority:
            return False
        expected = _sign(
            self._authority,
            {
                "token_id": self.token_id,
                "evidence_session_id": self.evidence_session_id,
                "query": self.query,
                "operation": self.operation,
                "coverage_universe_id": self.coverage_universe_id,
                "view_id": self.view_id,
                "ordering": self.ordering,
                "lineage_id": self.lineage_id,
                "cursor": self.cursor,
                "binding": self.binding.as_dict(),
                "has_more": True,
            },
        )
        return hmac.compare_digest(self._signature, expected)


@dataclass(frozen=True)
class EvidenceRecord:
    """Harness-issued evidence with explicit completeness and session lineage.

    A complete absence claim is accepted only through
    ``require_complete_absence_evidence`` with an explicit authenticated
    expected binding.  The duplicated top-level and embedded bindings make
    cross-field disagreement visible and rejectable.
    """

    evidence_id: str
    result: Any
    result_kind: str
    outcome: str
    support: str
    completeness: str
    termination: str
    binding: AuthenticatedBinding
    query: str
    operation: str
    coverage_universe_id: str
    view_id: str
    ordering: str
    evidence_session_id: str
    lineage_id: str
    has_more: bool
    continuation_cursor: Optional[str] = None
    partial: bool = False
    truncated: bool = False
    stale: bool = False
    available: bool = True
    top_level_binding: Optional[AuthenticatedBinding] = None
    embedded_binding: Optional[AuthenticatedBinding] = None
    _authority: Optional[_Authority] = field(default=None, repr=False, compare=False)
    _signature: str = field(default="", repr=False, compare=False)
    _raw_result: Any = field(default=None, init=False, repr=False, compare=False)

    def __post_init__(self) -> None:
        for name in (
            "evidence_id",
            "query",
            "operation",
            "coverage_universe_id",
            "view_id",
            "ordering",
            "evidence_session_id",
            "lineage_id",
        ):
            _require_text(getattr(self, name), name, identifier=True)
        if self.operation not in {
            "resolve",
            "definitions",
            "references",
            "implementations",
            "dependencies",
            "search",
            "source",
        }:
            raise ValidationError("evidence.operation is unsupported")
        if self.result_kind not in {"set", "mapping", "scalar"}:
            raise ValidationError("evidence.result_kind is unsupported")
        if self.outcome not in {
            "success",
            "available",
            "not_found",
            "empty_complete",
            "partial",
            "ambiguous",
            "unsupported",
            "unavailable",
            "stale",
            "budget_exhausted",
            "incomplete",
            "failed",
        }:
            raise ValidationError("evidence.outcome is unsupported")
        if self.support not in {"supported", "unsupported", "unavailable", "degraded"}:
            raise ValidationError("evidence.support is unsupported")
        if self.completeness not in {"complete", "partial", "unknown", "not_applicable"}:
            raise ValidationError("evidence.completeness is unsupported")
        if self.termination not in {
            "normal_terminal",
            "continuation_available",
            "truncated",
            "budget_exhausted",
            "stale",
            "failed",
            "unknown",
        }:
            raise ValidationError("evidence.termination is unsupported")
        _require_authenticated_binding(self.binding, "evidence.binding")
        for name in ("has_more", "partial", "truncated", "stale", "available"):
            _require_exact_bool(getattr(self, name), f"evidence.{name}")
        _optional_text(self.continuation_cursor, "continuation_cursor")
        if self.has_more is True and self.continuation_cursor is None:
            raise ValidationError("evidence with more results needs continuation state")
        if self.has_more is False and self.continuation_cursor is not None:
            raise ValidationError("terminal evidence cannot carry a continuation cursor")
        for name, value in (
            ("top_level_binding", self.top_level_binding),
            ("embedded_binding", self.embedded_binding),
        ):
            if value is not None:
                _require_authenticated_binding(value, f"evidence.{name}")
        top = self.top_level_binding if self.top_level_binding is not None else self.binding
        embedded = self.embedded_binding if self.embedded_binding is not None else self.binding
        object.__setattr__(self, "top_level_binding", top)
        object.__setattr__(self, "embedded_binding", embedded)
        object.__setattr__(self, "_raw_result", self.result)
        object.__setattr__(self, "result", _deep_freeze(_json_value(self.result, "evidence.result")))

    def is_authenticated(self) -> bool:
        """Return whether the exact record was issued by its harness."""

        if (
            self._authority is None
            or not isinstance(self.binding, AuthenticatedBinding)
            or self.binding._authority is not self._authority
            or not self.binding.is_authenticated()
            or not isinstance(self.top_level_binding, AuthenticatedBinding)
            or self.top_level_binding._authority is not self._authority
            or not self.top_level_binding.is_authenticated()
            or not isinstance(self.embedded_binding, AuthenticatedBinding)
            or self.embedded_binding._authority is not self._authority
            or not self.embedded_binding.is_authenticated()
        ):
            return False
        expected = _sign(self._authority, self._signed_payload())
        return hmac.compare_digest(self._signature, expected)

    def _signed_payload(self) -> dict[str, Any]:
        """Build the complete identity and outcome payload covered by the signature."""

        return {
            "evidence_id": self.evidence_id,
            "result": self.result,
            "result_kind": self.result_kind,
            "outcome": self.outcome,
            "support": self.support,
            "completeness": self.completeness,
            "termination": self.termination,
            "binding": self.binding.as_dict(),
            "top_level_binding": self.top_level_binding.as_dict(),
            "embedded_binding": self.embedded_binding.as_dict(),
            "source_id": self.top_level_binding.source_id,
            "materialization_id": self.top_level_binding.materialization_id,
            "configuration_id": self.top_level_binding.configuration_id,
            "generation_id": self.top_level_binding.generation_id,
            "query": self.query,
            "operation": self.operation,
            "coverage_universe_id": self.coverage_universe_id,
            "view_id": self.view_id,
            "ordering": self.ordering,
            "evidence_session_id": self.evidence_session_id,
            "lineage_id": self.lineage_id,
            "has_more": self.has_more,
            "continuation_cursor": self.continuation_cursor,
            "partial": self.partial,
            "truncated": self.truncated,
            "stale": self.stale,
            "available": self.available,
        }

    def as_dict(self) -> dict[str, Any]:
        """Return a fresh serialized record; it carries no private authority token."""

        return dict(self._signed_payload())


def _require_valid_evidence(evidence: Any, name: str = "evidence") -> EvidenceRecord:
    """Require a harness-issued immutable EvidenceRecord."""

    if not isinstance(evidence, EvidenceRecord) or not evidence.is_authenticated():
        raise ValidationError(f"{name} must be harness-authenticated evidence")
    return evidence


def validate_evidence(
    evidence: EvidenceRecord,
    expected_binding: AuthenticatedBinding,
) -> EvidenceRecord:
    """Validate an evidence record against an explicit authenticated binding.

    This is the general source/evidence join used before completeness,
    absence, or qualification-relevant interpretation.  A caller mapping or
    an omitted expected binding is never promoted to authenticated evidence.
    """

    record = _require_valid_evidence(evidence)
    expected = _require_authenticated_binding(expected_binding, "expected_binding")
    if record.binding._authority is not expected._authority:
        raise ValidationError("evidence and expected binding have different issuers")
    if _binding_tuple(record.binding) != _binding_tuple(expected):
        raise ValidationError("evidence binding does not match expected binding")
    if _binding_tuple(record.top_level_binding) != _binding_tuple(record.binding):
        raise ValidationError("top-level evidence binding disagrees")
    if _binding_tuple(record.embedded_binding) != _binding_tuple(record.binding):
        raise ValidationError("embedded evidence binding disagrees")
    top_level = record.top_level_binding.as_dict()
    if top_level != record.top_level_binding.as_dict():
        raise ValidationError("top-level identity fields disagree with embedded binding")
    return record


def validate_continuation(
    token: ContinuationToken,
    *,
    expected_binding: AuthenticatedBinding,
    evidence_session_id: str,
    query: str,
    operation: str,
    coverage_universe_id: str,
    view_id: str,
    ordering: str,
    lineage_id: str,
) -> bool:
    """Validate every continuation identity dimension before the next call."""

    if not isinstance(token, ContinuationToken) or not token.is_valid():
        raise ValidationError("continuation token is unauthenticated or mutated")
    _require_authenticated_binding(expected_binding, "expected_binding")
    for name, value in (
        ("evidence_session_id", evidence_session_id),
        ("query", query),
        ("operation", operation),
        ("coverage_universe_id", coverage_universe_id),
        ("view_id", view_id),
        ("ordering", ordering),
        ("lineage_id", lineage_id),
    ):
        _require_text(value, name, identifier=name != "query")
    if token.binding._authority is not expected_binding._authority:
        raise ValidationError("continuation and expected binding have different issuers")
    if _binding_tuple(token.binding) != _binding_tuple(expected_binding):
        raise ValidationError("continuation has the wrong source/configuration generation")
    if (
        token.evidence_session_id != evidence_session_id
        or token.query != query
        or token.operation != operation
        or token.coverage_universe_id != coverage_universe_id
        or token.view_id != view_id
        or token.ordering != ordering
        or token.lineage_id != lineage_id
    ):
        raise ValidationError("continuation lineage does not match the next call")
    return True


def require_complete_absence_evidence(
    evidence: EvidenceRecord,
    expected_binding: AuthenticatedBinding,
) -> EvidenceRecord:
    """Accept complete absence only with an explicit exact expected binding.

    Partial, stale, unavailable, unsupported, failed, truncated, budgeted,
    unknown, or malformed empty results are rejected rather than normalized to
    ``not_found`` or ``empty_complete``.
    """

    record = validate_evidence(evidence, expected_binding)
    if record.outcome not in {"success", "not_found", "empty_complete"}:
        raise ValidationError("non-success evidence cannot establish absence")
    if record.outcome == "not_found" and record.operation != "resolve":
        raise ValidationError("not_found is reserved for singular resolution")
    if record.support != "supported":
        raise ValidationError("unsupported or unavailable evidence cannot establish absence")
    if record.completeness != "complete":
        raise ValidationError("incomplete evidence cannot establish absence")
    if record.termination != "normal_terminal":
        raise ValidationError("non-terminal evidence cannot establish absence")
    if (
        record.has_more is not False
        or record.partial is not False
        or record.truncated is not False
        or record.stale is not False
        or record.available is not True
    ):
        raise ValidationError("limited, stale, or unavailable evidence cannot establish absence")
    if record.result_kind != "set" or not isinstance(record.result, tuple):
        raise ValidationError("absence requires an explicit empty result set")
    if len(record.result) != 0:
        raise ValidationError("absence evidence must contain an empty result set")
    if record.outcome == "success":
        # A successful empty result is normalized only after all complete gates above.
        return record
    if record.outcome not in {"not_found", "empty_complete"}:
        raise ValidationError("invalid absence outcome")
    return record


def validate_evidence_for_absence(
    evidence: EvidenceRecord,
    expected_binding: AuthenticatedBinding,
) -> bool:
    """Boolean convenience wrapper for the fail-closed absence validator."""

    require_complete_absence_evidence(evidence, expected_binding)
    return True
